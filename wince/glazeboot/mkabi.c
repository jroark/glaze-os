/*
 * Host program: prints glazeboot_abi.h, the constants and layouts the Windows
 * CE loader (GlazeBoot.c) shares with the kernel and the trampoline,
 * taken from glaze/bootinfo.h and plan.h so the two builds can't drift.
 * The Casio SDK has no <stdint.h>, so the structs are spelled in DWORD
 * and WORD, and the loader checks their sizes against these.
 */

#include <stddef.h>
#include <stdint.h>
#include <stdio.h>
#include <glaze/abi.h>
#include <glaze/bootinfo.h>
/* Only the layouts are wanted; keep plan.h's page access host-clean. */
#define GB_PAGE_PTR(frame)  ((uint32_t *)NULL + (frame))
#include "plan.h"

#define D(name, value)  printf("#define %-24s 0x%lxUL\n", name, (unsigned long)(value))

int main(void)
{
    printf("/* Generated by wince/glazeboot/mkabi.c from glaze/bootinfo.h and plan.h; do not edit. */\n");
    printf("#ifndef GLAZEBOOT_ABI_H\n#define GLAZEBOOT_ABI_H\n\n");

    D("GZ_BOOTINFO_MAGIC", GZ_BOOTINFO_MAGIC);
    D("GZ_BOOTINFO_VERSION", GZ_BOOTINFO_VERSION);
    D("GZ_BOOTINFO_PA", GZ_BOOTINFO_PA);
    D("GZ_BOOT_NAND_RW", GZ_BOOT_NAND_RW);
    D("GZ_BOOT_NAND_OFF", GZ_BOOT_NAND_OFF);
    D("GZ_TRACE_FB", GZ_TRACE_FB);
    D("GZ_TRACE_STRIDE", GZ_TRACE_STRIDE);
    D("GZ_KERNEL_BIN_MAGIC", GZ_KERNEL_BIN_MAGIC);
    D("GZ_KERNEL_BIN_HEADER", GZ_KERNEL_BIN_HEADER);
    D("GZ_FLASH_BLOCKS", GZ_FLASH_BLOCKS);
    D("GB_PAGE", GB_PAGE);
    D("GB_FRAMES", GB_FRAMES);
    D("GB_MOVES_PER_PAGE", GB_MOVES_PER_PAGE);
    D("GB_MAX_MOVE_PAGES", GB_MAX_MOVE_PAGES);
    D("GB_MAX_MOVES", GB_MAX_MOVES);
    D("GB_WHO_PAGES", GB_WHO_PAGES);
    D("GB_CONTROL_MAGIC", GB_CONTROL_MAGIC);
    printf("\n");

    printf("typedef struct gz_bootinfo {\n"
           "    DWORD magic, version, flags;\n"
           "    DWORD romfs_pa, romfs_size;\n"
           "    DWORD ramfs_pa, ramfs_blocks;\n"
           "    DWORD reserved;\n"
           "} gz_bootinfo;\n");
    D("GZ_BOOTINFO_SIZE", sizeof(struct gz_bootinfo));
    printf("typedef struct gz_kernel_bin {\n"
           "    DWORD magic;\n"
           "    DWORD load, entry, size;\n"
           "    DWORD end;\n"
           "    DWORD reserved[3];\n"
           "} gz_kernel_bin;\n");
    D("GZ_KERNEL_BIN_SIZE", sizeof(struct gz_kernel_bin));
    printf("typedef struct gb_move {\n"
           "    WORD src, dst;\n"
           "    WORD where;\n"
           "    WORD pad;\n"
           "} gb_move;\n");
    D("GB_MOVE_SIZE", sizeof(struct gb_move));
    printf("typedef struct gb_control {\n"
           "    DWORD magic;\n"
           "    DWORD count;\n"
           "    DWORD entry;\n"
           "    DWORD arg;\n"
           "    DWORD move_frames[GB_MAX_MOVE_PAGES];\n"
           "    DWORD who_frames[GB_WHO_PAGES];\n"
           "} gb_control;\n");
    D("GB_CONTROL_SIZE", sizeof(struct gb_control));
    printf("\n#endif\n");
    return 0;
}
