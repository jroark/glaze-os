/*
 * Host program: prints glazeboot_abi.h, the constants and layouts the eVC
 * loader (evc/GlazeBoot.cpp) shares with the kernel and the trampoline,
 * taken from glaze/bootinfo.h and plan.h so the two builds can't drift.
 * eVC's compiler has no <stdint.h>, so the structs are spelled in DWORD
 * and WORD, and the loader checks their sizes against these.
 */

#include <stddef.h>
#include <stdint.h>
#include <stdio.h>
#include <glaze/abi.h>
#include <glaze/bootinfo.h>
/* Only the layouts are wanted; keep plan.h's page access host-clean. */
#define GB_PAGE_PTR(frame)  ((uint32_t *)NULL + (frame))
#include "plan.h"

#define D(name, value)  printf("#define %-24s 0x%lxUL\r\n", name, (unsigned long)(value))

int main(void)
{
    printf("/* Generated by wince/glazeboot/mkabi.c from glaze/bootinfo.h and plan.h; do not edit. */\r\n");
    printf("#ifndef GLAZEBOOT_ABI_H\r\n#define GLAZEBOOT_ABI_H\r\n\r\n");

    D("GZ_BOOTINFO_MAGIC", GZ_BOOTINFO_MAGIC);
    D("GZ_BOOTINFO_VERSION", GZ_BOOTINFO_VERSION);
    D("GZ_BOOTINFO_PA", GZ_BOOTINFO_PA);
    D("GZ_BOOT_NAND_RW", GZ_BOOT_NAND_RW);
    D("GZ_KERNEL_BIN_MAGIC", GZ_KERNEL_BIN_MAGIC);
    D("GZ_KERNEL_BIN_HEADER", GZ_KERNEL_BIN_HEADER);
    D("GZ_FLASH_BLOCKS", GZ_FLASH_BLOCKS);
    D("GB_PAGE", GB_PAGE);
    D("GB_FRAMES", GB_FRAMES);
    D("GB_MOVES_PER_PAGE", GB_MOVES_PER_PAGE);
    D("GB_MAX_MOVE_PAGES", GB_MAX_MOVE_PAGES);
    D("GB_MAX_MOVES", GB_MAX_MOVES);
    D("GB_WHO_PAGES", GB_WHO_PAGES);
    D("GB_CONTROL_MAGIC", GB_CONTROL_MAGIC);
    printf("\r\n");

    printf("struct gz_bootinfo {\r\n"
           "    DWORD magic, version, flags;\r\n"
           "    DWORD romfs_pa, romfs_size;\r\n"
           "    DWORD ramfs_pa, ramfs_blocks;\r\n"
           "    DWORD reserved;\r\n"
           "};\r\n");
    D("GZ_BOOTINFO_SIZE", sizeof(struct gz_bootinfo));
    printf("struct gz_kernel_bin {\r\n"
           "    DWORD magic;\r\n"
           "    DWORD load, entry, size;\r\n"
           "    DWORD end;\r\n"
           "    DWORD reserved[3];\r\n"
           "};\r\n");
    D("GZ_KERNEL_BIN_SIZE", sizeof(struct gz_kernel_bin));
    printf("struct gb_move {\r\n"
           "    WORD src, dst;\r\n"
           "    WORD where;\r\n"
           "    WORD pad;\r\n"
           "};\r\n");
    D("GB_MOVE_SIZE", sizeof(struct gb_move));
    printf("struct gb_control {\r\n"
           "    DWORD magic;\r\n"
           "    DWORD count;\r\n"
           "    DWORD entry;\r\n"
           "    DWORD arg;\r\n"
           "    DWORD move_frames[GB_MAX_MOVE_PAGES];\r\n"
           "    DWORD who_frames[GB_WHO_PAGES];\r\n"
           "};\r\n");
    D("GB_CONTROL_SIZE", sizeof(struct gb_control));
    printf("\r\n#endif\r\n");
    return 0;
}
