#!/usr/bin/env python3
"""Write GlazeBoot's trampoline as a C header for the Windows CE
loader (wince/glazeboot/GlazeBoot.c): the code as a DWORD array, so it is word aligned,
and the offsets of its entry points.

usage: tools/mktrampblob.py tramp.bin tramp.sym out.h
  tramp.bin  objcopy -O binary of the trampoline linked at 0 (tramp.lds)
  tramp.sym  `nm` output for the same link
"""

import sys

code = open(sys.argv[1], "rb").read()
code += b"\0" * (-len(code) % 4)
symbols = {}
for line in open(sys.argv[2]):
    parts = line.split()
    if len(parts) == 3:
        symbols[parts[2]] = int(parts[0], 16)
for name in ("tramp_entry", "tramp_read_c0"):
    if name not in symbols:
        sys.exit(f"mktrampblob: no {name} in {sys.argv[2]}")
if symbols["tramp_entry"] != 0:
    sys.exit("mktrampblob: tramp_entry must be at offset 0")
if len(code) > 4096:
    sys.exit(f"mktrampblob: the trampoline ({len(code)} bytes) must fit in a page")

words = [int.from_bytes(code[i:i + 4], "little") for i in range(0, len(code), 4)]
lines = [
    "/* Generated by tools/mktrampblob.py from wince/glazeboot/tramp.c; do not edit. */",
    "#ifndef GLAZEBOOT_TRAMP_BLOB_H",
    "#define GLAZEBOOT_TRAMP_BLOB_H",
    "",
    f"#define TRAMP_BYTES        {len(code)}",
    f"#define TRAMP_ENTRY        0x{symbols['tramp_entry']:x}   /* (control page KSEG0) */",
    f"#define TRAMP_READ_C0      0x{symbols['tramp_read_c0']:x}   /* (0 Status, 1 PRId, 2 Config) */",
    "",
    "static const DWORD tramp_code[] = {",
]
for i in range(0, len(words), 6):
    lines.append("    " + ", ".join(f"0x{w:08x}" for w in words[i:i + 6]) + ",")
lines += ["};", "", "#endif", ""]
open(sys.argv[3], "w").write("\n".join(lines))
