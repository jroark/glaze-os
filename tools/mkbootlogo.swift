// Renders the boot splash's "Glaze" wordmark (Vera Bold) as 4-bit alpha
// into boot/bootlogo.h, which is checked in: the SPL and kernel draw it with
// no font or image code (boot/splash.h).
//
//   swift tools/mkbootlogo.swift > boot/bootlogo.h

import CoreGraphics
import CoreText
import Foundation

let text = "Glaze"
let size: CGFloat = 40
let font = URL(fileURLWithPath: "assets/fonts/VeraBd.ttf")

guard let provider = CGDataProvider(url: font as CFURL),
      let cgFont = CGFont(provider) else {
    FileHandle.standardError.write("mkbootlogo: cannot load \(font.path)\n".data(using: .utf8)!)
    exit(1)
}
let ctFont = CTFontCreateWithGraphicsFont(cgFont, size, nil, nil)
let attr = NSAttributedString(string: text, attributes: [
    NSAttributedString.Key(kCTFontAttributeName as String): ctFont,
    NSAttributedString.Key(kCTForegroundColorFromContextAttributeName as String): true,
])
let line = CTLineCreateWithAttributedString(attr)
let bounds = CTLineGetBoundsWithOptions(line, .useGlyphPathBounds)
let w = Int(ceil(bounds.width)) + 2, h = Int(ceil(bounds.height)) + 2

let ctx = CGContext(data: nil, width: w, height: h, bitsPerComponent: 8, bytesPerRow: w,
                    space: CGColorSpaceCreateDeviceGray(), bitmapInfo: CGImageAlphaInfo.none.rawValue)!
ctx.setFillColor(gray: 0, alpha: 1)
ctx.fill(CGRect(x: 0, y: 0, width: w, height: h))
ctx.setFillColor(gray: 1, alpha: 1)
ctx.textPosition = CGPoint(x: 1 - bounds.minX, y: 1 - bounds.minY)
CTLineDraw(line, ctx)

let px = ctx.data!.bindMemory(to: UInt8.self, capacity: w * h)
var out = "/* Generated by tools/mkbootlogo.swift from assets/fonts/VeraBd.ttf; do not edit. */\n"
out += "#define BOOTLOGO_W \(w)\n#define BOOTLOGO_H \(h)\n"
out += "/* 4-bit alpha, two pixels a byte (low nibble first), rows top down. */\n"
out += "static const unsigned char bootlogo[] = {\n"
var bytes: [UInt8] = []
for y in 0..<h {
    var x = 0
    while x < w {
        let a = UInt8((Int(px[y * w + x]) + 8) / 17)
        let b = x + 1 < w ? UInt8((Int(px[y * w + x + 1]) + 8) / 17) : 0
        bytes.append(a | (b << 4))
        x += 2
    }
}
for i in stride(from: 0, to: bytes.count, by: 16) {
    out += "   " + bytes[i..<min(i + 16, bytes.count)].map { String(format: " 0x%02x,", $0) }.joined() + "\n"
}
out += "};\n"
print(out, terminator: "")
