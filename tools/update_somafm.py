#!/usr/bin/env python3
"""Refresh the checked-in MP3 station catalog from SomaFM's public listen page.

Usage: python3 tools/update_somafm.py [downloaded-listen.html]
No catalog API or runtime scraping; builds use the checked-in header.
"""
import html
import json
from pathlib import Path
import re
import sys
from urllib.request import urlopen


def catalog(page):
    stations = []
    for block in re.split(r"<!-- Channel: ", page)[1:]:
        station_id = block.split()[0]
        name = re.search(r"<h3>(.*?)</h3>", block, re.S)
        genre = re.search(r"<!-- .*?\((.*?)\) -->", block)
        links = re.search(r"MP3 PLS \(SSL\): (.*?)(?:<br|</nobr>)", block, re.S)
        urls = re.findall(r'href="(/[^"<>]+\.pls)"[^>]*>(\d+)k', links[1]) if links else []
        urls = [(url, int(rate)) for url, rate in urls if not url.startswith('/nossl/')]
        if not name or not urls:
            continue
        url, rate = min(urls, key=lambda item: (item[1] != 128, item[1]))
        stations.append((station_id, html.unescape(name[1]),
                         html.unescape(genre[1]).replace('/', ' / ') if genre else 'Live radio',
                         'https://somafm.com' + url, rate))
    if len(stations) < 20 or len({s[0] for s in stations}) != len(stations):
        raise ValueError('Station page changed; inspect it before updating the catalog')
    return sorted(stations, key=lambda s: s[1].casefold())


def main():
    page = Path(sys.argv[1]).read_text() if len(sys.argv) > 1 else urlopen(
        'https://somafm.com/listen/', timeout=30).read().decode()
    stations = catalog(page)
    target = Path(__file__).resolve().parents[1] / 'packages/somafm/stations.h'
    target.parent.mkdir(parents=True, exist_ok=True)
    content = ('/* Generated by tools/update_somafm.py from https://somafm.com/listen/ */\n'
               '#ifndef SOMAFM_STATIONS_H\n#define SOMAFM_STATIONS_H\n'
               'struct station { const char *id, *name, *genre, *playlist; int bitrate; };\n'
               'static const struct station stations[] = {\n')
    for station in stations:
        content += '    {' + ', '.join(json.dumps(s, ensure_ascii=True) for s in station) + '},\n'
    content += '};\n#define STATION_COUNT ((int)(sizeof(stations) / sizeof(stations[0])))\n#endif\n'
    target.write_text(content)
    print(f'{len(stations)} MP3 stations -> {target}')


if __name__ == '__main__':
    main()
