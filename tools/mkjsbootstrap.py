#!/usr/bin/env python3
"""Embed the browser's DOM bindings, without requiring filesystem JavaScript."""
import json
import pathlib
import sys
src, dst = map(pathlib.Path, sys.argv[1:])
dst.parent.mkdir(parents=True, exist_ok=True)
text = src.read_text().replace("/* WEB_APIS */", (src.parent / "js_web.js").read_text())
dst.write_text('/* Generated by tools/mkjsbootstrap.py. */\nstatic const char js_bootstrap[] =\n' +
               '\n'.join(json.dumps(line + '\n', ensure_ascii=True) for line in text.splitlines()) + ';\n')
