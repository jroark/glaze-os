#!/usr/bin/env python3
"""Writes lib/gps/gps_tables.h: integer tables for lib/gps/gps.c.

MERC_Y[i] and MERC_D[i] are Web Mercator's y = ln tan(pi/4 + lat/2) and its
derivative (sec lat) at lat = i/4 degree, in world units (2^31 = pi), the
derivative per quarter-degree step: cubic Hermite between them is exact to
well under a world unit at zoom 18. COS_Q16[i] is cos(i degrees) * 65536.
"""
import math, sys
STEP = 0.25
N = int(85.25 / STEP) + 2
y = [round(math.log(math.tan(math.pi / 4 + math.radians(i * STEP) / 2)) * 2**31 / math.pi) for i in range(N)]
d = [round(1 / math.cos(math.radians(i * STEP)) * 2**31 / 180 * STEP) for i in range(N)]
c = [round(math.cos(math.radians(i)) * 65536) for i in range(91)]
def rows(v):
    return "\n".join("    " + ", ".join(str(x) for x in v[i:i + 8]) + "," for i in range(0, len(v), 8))
out = sys.argv[1] if len(sys.argv) > 1 else "lib/gps/gps_tables.h"
with open(out, "w") as f:
    f.write("/* Generated by tools/mkmercator.py; do not edit. */\n")
    f.write(f"#define MERC_STEP_E7 {int(STEP * 1e7)}\n#define MERC_ENTRIES {N}\n")
    f.write(f"static const uint32_t MERC_Y[MERC_ENTRIES] = {{\n{rows(y)}\n}};\n")
    f.write(f"static const uint32_t MERC_D[MERC_ENTRIES] = {{\n{rows(d)}\n}};\n")
    f.write(f"static const uint32_t COS_Q16[91] = {{\n{rows(c)}\n}};\n")
